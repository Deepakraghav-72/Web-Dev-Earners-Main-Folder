// If-else statment .
// find out the student grade based on the marks obtained.
let marks = 25;

if (marks >= 90) {
    console.log("Grade: A");
} else if (marks >= 80) {
    console.log("grade: B");
} else if (marks >= 70) {
    console.log("grade: C");
} else if (marks >= 60) {
    console.log("grade: D");
} else if (marks >= 50) {
    console.log("grade: E");
} else if (marks >= 40) {
    console.log("grade: F");
} else {
    console.log("Fail");
}